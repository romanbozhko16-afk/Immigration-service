"""List the fillable fields of an official USCIS PDF (read-only).

Usage: uv run python -I scripts/list_pdf_fields.py FORM.pdf OUT.json OUT.md

Writes a machine-readable JSON and a human-readable Markdown table. USCIS forms are
hybrid XFA + AcroForm PDFs; this lists the AcroForm widgets, which is what pypdf can fill.
"""

import json
import re
import sys
from pathlib import Path

from pypdf import PdfReader

STATE_CODES_MARKER = "['AA', 'AA']"


def _clean(value: object) -> str | None:
    text = str(value).strip() if value not in (None, "") else ""
    return text or None


def collect(reader: PdfReader) -> list[dict]:
    rows = []
    for name, field in (reader.get_fields() or {}).items():
        field_type = field.get("/FT")
        if field_type is None:  # container node, not a fillable widget
            continue
        page_match = re.search(r"Page(\d+)\[", name)
        is_barcode = "PDF417BarCode" in name
        states = [str(s) for s in (field.get("/_States_") or [])]
        rows.append(
            {
                "name": name.removeprefix("form1[0]."),
                "type": {"/Tx": "text", "/Btn": "checkbox", "/Ch": "choice"}.get(
                    str(field_type), str(field_type)
                ),
                "page": int(page_match.group(1)) if page_match else None,
                "max_length": field.get("/MaxLen"),
                "options": states,
                "tooltip": _clean(field.get("/TU")),
                "is_barcode": is_barcode,
            }
        )
    return rows


def describe_options(row: dict) -> str:
    options = row["options"]
    if not options:
        return ""
    if any(STATE_CODES_MARKER in o for o in options):
        return f"choice list: {len(options)} entries (US state / territory codes)"
    # Checkbox on-value is the entry that is not /Off.
    return ", ".join(o for o in options if o != "/Off")


def render_markdown(rows: list[dict], source: str) -> str:
    fillable = [r for r in rows if not r["is_barcode"]]
    lines = [
        f"# Fields of `{source}`",
        "",
        f"Generated by `scripts/list_pdf_fields.py`. {len(fillable)} fillable fields "
        f"(+ {len(rows) - len(fillable)} barcode fields that must never be filled).",
        "",
        "**Mapping warning:** PDF field *names* often do not match the printed item numbers "
        "(for example `Line9_Checkbox` is item 10, Sex). Always map by the tooltip text, "
        "which carries the real Part and item number.",
        "",
    ]
    by_page: dict[int | None, list[dict]] = {}
    for row in fillable:
        by_page.setdefault(row["page"], []).append(row)
    for page in sorted(by_page, key=lambda p: (p is None, p)):
        lines += [f"## Page {page}", "", "| PDF field | Type | Max | Value / options | Tooltip |"]
        lines.append("|---|---|---|---|---|")
        for row in by_page[page]:
            tip = (row["tooltip"] or "").replace("|", "/")
            lines.append(
                f"| `{row['name'].split('.', 1)[-1]}` | {row['type']} | "
                f"{row['max_length'] or ''} | {describe_options(row)} | {tip} |"
            )
        lines.append("")
    return "\n".join(lines)


def main(pdf_path: str, json_out: str, md_out: str) -> None:
    reader = PdfReader(pdf_path)
    rows = collect(reader)
    Path(json_out).write_text(json.dumps(rows, indent=1, ensure_ascii=False) + "\n")
    Path(md_out).write_text(render_markdown(rows, Path(pdf_path).name) + "\n")
    counts = {t: sum(1 for r in rows if r["type"] == t) for t in ("text", "checkbox", "choice")}
    print(f"{len(rows)} widgets: {counts}; barcodes: {sum(r['is_barcode'] for r in rows)}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
